import { useState } from "react";
import { FileSearch, ShieldCheck, Upload } from "lucide-react";
import DetectionPageShell from "../components/DetectionPageShell";
import DetectionDetailsDrawer from "../components/DetectionDetailsDrawer";
import NewDetectionForm from "../components/NewDetectionForm";

export default function NewDetectionPage() {
  const [result, setResult] = useState(null);
  const [batch, setBatch] = useState(null);

  function handleComplete(value) {
    if (Array.isArray(value?.items)) {
      setBatch(value);
      setResult(null);
    } else {
      setBatch(null);
      setResult(value);
    }
  }

  return (
    <DetectionPageShell
      page="new"
      title="New Detection"
      description="Submit an email for prediction, risk assessment, and optional behavioral analysis."
      selectedDetection={null}
      onCloseDetection={() => {}}
    >
      <div className="det-new-layout">
        <section className="det-panel det-new-panel">
          <header>
            <div>
              <h2>Analyze an Email</h2>
              <p>Use a parsed email with extracted features or upload a raw .eml file.</p>
            </div>
          </header>
          <NewDetectionForm onComplete={handleComplete} />
        </section>

        <aside className="det-panel det-workflow-card">
          <h2>Detection workflow</h2>
          <ol>
            <li><span><Upload size={16}/></span><div><strong>Choose an input</strong><small>Use Email Collection or submit an .eml file.</small></div></li>
            <li><span><FileSearch size={16}/></span><div><strong>Extract and prepare features</strong><small>The backend uses the saved feature vector or parses the uploaded message.</small></div></li>
            <li><span><ShieldCheck size={16}/></span><div><strong>Run the active model</strong><small>Prediction and enabled analysis results are returned by the API.</small></div></li>
          </ol>
          <p className="det-note">Predictions, confidence, risk scores, and analysis results are never generated by the UI.</p>
        </aside>
      </div>

      {batch && <section className="det-panel det-batch-results" aria-live="polite">
        <header><div><h2>Batch results</h2><p>{batch.succeeded_count} completed · {batch.failed_count} failed · batch {String(batch.batch_id).slice(0, 8)}</p></div></header>
        <div className="det-batch-table-wrap"><table className="det-batch-table"><thead><tr><th>Input</th><th>Result</th><th>Status</th><th>Details</th></tr></thead><tbody>
          {batch.items.map((item, index) => <tr key={`${item.detection?.id || item.email_id || item.filename}-${index}`}>
            <td>{item.filename || item.detection?.email_subject || item.email_id}</td>
            <td>{item.detection ? `${item.detection.predicted_label} · ${item.detection.confidence == null ? "—" : `${(item.detection.confidence * 100).toFixed(1)}%`}` : item.error}</td>
            <td><span className={`det-batch-status ${item.status === "completed" ? "is-complete" : "is-failed"}`}>{item.status}</span></td>
            <td>{item.detection && <button type="button" className="det-secondary" onClick={() => setResult(item.detection)}>View</button>}</td>
          </tr>)}
        </tbody></table></div>
      </section>}

      <DetectionDetailsDrawer item={result} onClose={() => setResult(null)} />
    </DetectionPageShell>
  );
}
