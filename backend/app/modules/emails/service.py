# ============================================================================
# CONSTANTS
# ============================================================================

DEFAULT_PAGE_SIZE = 30
MAX_PAGE_SIZE = 100
logger = logging.getLogger(__name__)


# ============================================================================
# SERVICE EXCEPTIONS
# ============================================================================


class EmailAlreadyExistsError(Exception):
    """
    Raised when identical email content already exists.
    """


class EmailNotFoundError(Exception):
    """
    Raised when an email record does not exist.
    """


class EmailIngestionError(Exception):
    """
    Raised when email ingestion fails.
    """


# ============================================================================
# EMAIL SERVICE
# ============================================================================


class EmailService:
    """
    Application service for Module 02 — Email Management.

    Responsibilities:
        - Validate labeled email ingestion requests.
        - Ingest raw email content.
        - Ingest .eml files.
        - Support bulk .eml ingestion.
        - Prevent duplicate email ingestion.
        - Persist ground-truth labels.
        - Persist ingestion-level email metadata.
        - Retrieve emails with filters and pagination.
        - Provide email statistics.
        - Build detailed email responses.

    Email Details include:
        - Ground truth
        - Source
        - Source identifier
        - Subject
        - Sender
        - Recipients
        - CC
        - BCC
        - Reply-To
        - Message-ID
        - Received At
        - Collected At
        - Content Type
        - MIME Version
        - Content Hash
        - Email ID
        - Raw email content

    Explicitly outside this service:
        - Feature extraction
        - Dataset creation
        - Preprocessing
        - Machine learning
        - Prediction
        - Confidence scoring
        - Risk scoring
        - Threat analysis
        - Detection decisions

    Ground-truth labels are supplied by the controlled ingestion
    workflow and are never generated by this service.
    """

    def __init__(
        self,
        repository: EmailRepository,
    ) -> None:
        if repository is None:
            raise ValueError(
                "Email repository is required."
            )

        self.repository = repository
        self.collector = EmailCollector()

    # ========================================================================
    # RAW EMAIL INGESTION
    # ========================================================================

    def ingest(
        self,
        request: EmailIngestRequest,
    ) -> Email:
        """
        Ingest one raw email.

        RAW_EMAIL is always used as the source.

        The ground-truth label is supplied by the caller and is
        persisted exactly as provided.
        """

        self._validate_ingest_request(
            request,
        )

        try:
            collected = self.collector.collect_text(
                request.raw_content,
            )
        except Exception as exc:
            raise EmailIngestionError(
                "Failed to process the supplied raw email content."
            ) from exc

        return self._ingest_collected_email(
            collected=collected,
            source=EmailSource.RAW_EMAIL,
            source_identifier=request.source_identifier,
            ground_truth_label=request.ground_truth_label,
        )

    # ========================================================================
    # FILE INGESTION
    # ========================================================================

    def ingest_file(
        self,
        raw_data: bytes,
        *,
        ground_truth_label: EmailGroundTruthLabel,
        source_identifier: str | None = None,
    ) -> Email:
        """
        Ingest one .eml file.

        The file and ground-truth label are treated as one
        ingestion operation.
        """

        if not raw_data:
            raise EmailIngestionError(
                "The uploaded .eml file is empty."
            )

        if ground_truth_label is None:
            raise EmailIngestionError(
                "Ground-truth label is required."
            )

        try:
            collected = self.collector.collect_bytes(
                raw_data,
            )
        except Exception as exc:
            raise EmailIngestionError(
                "Failed to process the uploaded .eml file."
            ) from exc

        return self._ingest_collected_email(
            collected=collected,
            source=EmailSource.FILE_UPLOAD,
            source_identifier=source_identifier,
            ground_truth_label=ground_truth_label,
        )

    # ========================================================================
    # BULK FILE INGESTION
    # ========================================================================

    def ingest_files(
        self,
        files: list[tuple[str, bytes]],
        *,
        ground_truth_label: EmailGroundTruthLabel,
    ) -> EmailBulkUploadResponse:
        """
        Ingest multiple .eml files as one labeled batch.

        Every file in the batch receives the same ground-truth label.

        Duplicate files do not stop the remaining files.

        Individual file failures do not stop the batch.
        """

        if not files:
            raise EmailIngestionError(
                "At least one .eml file is required."
            )

        if ground_truth_label is None:
            raise EmailIngestionError(
                "Ground-truth label is required for the batch."
            )

        results: list[EmailUploadResult] = []

        successful = 0
        duplicates = 0
        failed = 0

        for filename, raw_data in files:
            normalized_filename = (
                filename.strip()
                if filename
                else "unknown.eml"
            )

            try:
                email = self.ingest_file(
                    raw_data,
                    ground_truth_label=ground_truth_label,
                    source_identifier=normalized_filename,
                )

                results.append(
                    EmailUploadResult(
                        filename=normalized_filename,
                        email_id=email.id,
                        source=EmailSource.FILE_UPLOAD,
                        ground_truth_label=(
                            email.ground_truth_label
                        ),
                        status=email.status,
                        duplicate=False,
                        error=None,
                    )
                )

                successful += 1

            except EmailAlreadyExistsError as exc:
                existing = self._find_duplicate(
                    raw_data,
                )

                results.append(
                    EmailUploadResult(
                        filename=normalized_filename,
                        email_id=(
                            existing.id
                            if existing is not None
                            else None
                        ),
                        source=EmailSource.FILE_UPLOAD,
                        ground_truth_label=ground_truth_label,
                        status=(
                            existing.status
                            if existing is not None
                            else EmailStatus.FAILED
                        ),
                        duplicate=True,
                        error=str(exc),
                    )
                )

                duplicates += 1

            except Exception as exc:
                results.append(
                    EmailUploadResult(
                        filename=normalized_filename,
                        email_id=None,
                        source=EmailSource.FILE_UPLOAD,
                        ground_truth_label=ground_truth_label,
                        status=EmailStatus.FAILED,
                        duplicate=False,
                        error=str(exc),
                    )
                )

                failed += 1

        return EmailBulkUploadResponse(
            total_files=len(files),
            successful=successful,
            duplicates=duplicates,
            failed=failed,
            items=results,
        )

    # ========================================================================
    # COMMON INGESTION
    # ========================================================================

    def _ingest_collected_email(
        self,
        *,
        collected: CollectedEmail,
        source: EmailSource,
        source_identifier: str | None,
        ground_truth_label: EmailGroundTruthLabel,
    ) -> Email:
        """
        Persist one collected email.

        RAW_EMAIL and FILE_UPLOAD use the same persistence rules.

        Duplicate detection is based on content_hash.

        All ingestion-level metadata comes from CollectedEmail.
        """

        if ground_truth_label is None:
            raise EmailIngestionError(
                "Ground-truth label is required."
            )

        existing = self.repository.get_by_content_hash(
            collected.content_hash,
        )

        if existing is not None:
            raise EmailAlreadyExistsError(
                "An email with the same content has already "
                "been ingested."
            )

        email = Email(
            source=source,

            source_identifier=source_identifier,

            ground_truth_label=ground_truth_label,

            message_id=collected.message_id,

            sender=collected.sender,

            recipients=collected.recipients,

            cc=collected.cc,

            bcc=collected.bcc,

            reply_to=collected.reply_to,

            subject=collected.subject,

            content_type=collected.content_type,

            mime_version=collected.mime_version,

            raw_content=collected.raw_content,

            content_hash=collected.content_hash,

            received_at=self._resolve_received_at(
                collected.received_at,
            ),

            collected_at=datetime.now(
                timezone.utc,
            ),

            status=EmailStatus.INGESTED,
        )

        try:
            email = self.repository.create(
                email,
            )
            # Threat Intelligence is an optional consumer of canonical Email
            # records. A matching failure must not undo valid email ingestion.
            try:
                from app.modules.threat_intelligence.service import ThreatService
                ThreatService(self.repository.db).reconcile_email(email)
            except Exception:
                logger.exception("Threat indicator matching failed for ingested email %s", email.id)
            return email
        except Exception as exc:
            raise EmailIngestionError(
                "Failed to persist the email record."
            ) from exc

    # ========================================================================
    # RECEIVED TIMESTAMP
    # ========================================================================

    @staticmethod
    def _resolve_received_at(
        collected_received_at: datetime | None,
    ) -> datetime | None:
        """
        Normalize the received timestamp to UTC.

        The collector already parses the email Date header.
        """

        if collected_received_at is None:
            return None

        if collected_received_at.tzinfo is None:
            collected_received_at = (
                collected_received_at.replace(
                    tzinfo=timezone.utc,
                )
            )

        return collected_received_at.astimezone(
            timezone.utc,
        )

    # ========================================================================
    # DUPLICATE LOOKUP
    # ========================================================================

    def _find_duplicate(
        self,
        raw_data: bytes,
    ) -> Email | None:
        """
        Resolve the existing email for a duplicate upload.

        This method is used only for bulk-upload reporting.
        """

        try:
            collected = self.collector.collect_bytes(
                raw_data,
            )
        except Exception:
            return None

        return self.repository.get_by_content_hash(
            collected.content_hash,
        )

    # ========================================================================
    # INGESTION VALIDATION
    # ========================================================================

    @staticmethod
    def _validate_ingest_request(
        request: EmailIngestRequest,
    ) -> None:
        """
        Validate a raw-email ingestion request.
        """

        if request is None:
            raise EmailIngestionError(
                "Ingestion request is required."
            )

        if not request.raw_content.strip():
            raise EmailIngestionError(
                "Raw email content cannot be empty."
            )

        if request.ground_truth_label is None:
            raise EmailIngestionError(
                "Ground-truth label is required."
            )

        if request.source_identifier is not None:
            if not request.source_identifier.strip():
                raise EmailIngestionError(
                    "Source identifier cannot be empty."
                )

    # ========================================================================
    # EMAIL RETRIEVAL
    # ========================================================================

    def get(
        self,
        email_id: UUID,
    ) -> Email:
        """
        Return one stored email by UUID.
        """

        email = self.repository.get_by_id(
            email_id,
        )

        if email is None:
            raise EmailNotFoundError(
                f"Email '{email_id}' was not found."
            )

        return email

    # ========================================================================
    # EMAIL LIST
    # ========================================================================

    def list(
        self,
        query: EmailListQuery | None = None,
        *,
        page: int | None = None,
        page_size: int | None = None,
    ) -> tuple[list[Email], int]:
        """
        Return filtered and paginated email records.

        Supports:
            - EmailListQuery
            - Direct page/page_size arguments
        """

        if query is not None:
            resolved_page = query.page
            resolved_page_size = query.page_size

            search = query.search
            source = query.source
            ground_truth_label = query.status
            from_date = query.from_date
            to_date = query.to_date

        else:
            resolved_page = (
                page
                if page is not None
                else 1
            )

            resolved_page_size = (
                page_size
                if page_size is not None
                else DEFAULT_PAGE_SIZE
            )

            search = None
            source = None
            ground_truth_label = None
            from_date = None
            to_date = None

        resolved_page = max(
            resolved_page,
            1,
        )

        resolved_page_size = max(
            1,
            min(
                resolved_page_size,
                MAX_PAGE_SIZE,
            ),
        )

        return self.repository.list(
            page=resolved_page,
            page_size=resolved_page_size,
            search=search,
            source=source,
            ground_truth_label=ground_truth_label,
            from_date=from_date,
            to_date=to_date,
        )

    # ========================================================================
    # EMAIL LIST RESPONSE
    # ========================================================================

    def get_list_response(
        self,
        query: EmailListQuery,
    ) -> EmailListResponse:
        """
        Build the API-facing paginated email list response.

        The response is intentionally flat:

            items
            total
            page
            page_size
            total_pages
            start_index
            end_index

        Empty result sets use total_pages=1 to satisfy the
        EmailListResponse validation contract.
        """

        items, total = self.list(
            query,
        )

        page = max(
            query.page,
            1,
        )

        page_size = max(
            1,
            min(
                query.page_size,
                MAX_PAGE_SIZE,
            ),
        )

        total_pages = max(
            1,
            (
                (total + page_size - 1)
                // page_size
                if total > 0
                else 1
            ),
        )

        response_items = [
            self._to_email_response(
                email,
            )
            for email in items
        ]

        if total > 0:
            start_index = (
                ((page - 1) * page_size)
                + 1
            )

            end_index = min(
                page * page_size,
                total,
            )

        else:
            start_index = 0
            end_index = 0

        return EmailListResponse(
            items=response_items,
            total=total,
            page=page,
            page_size=page_size,
            total_pages=total_pages,
            start_index=start_index,
            end_index=end_index,
        )

    # ========================================================================
    # EMAIL DETAIL
    # ========================================================================

    def get_detail(
        self,
        email_id: UUID,
    ) -> EmailDetailResponse:
        """
        Return the complete Email Details representation.

        The raw email content is included because this response
        powers the Email Details drawer.
        """

        email = self.get(
            email_id,
        )

        return self._to_email_detail_response(
            email,
        )

    # ========================================================================
    # EMAIL STATISTICS
    # ========================================================================

    def get_statistics(
        self,
    ) -> EmailStatisticsResponse:
        """
        Return Email Management ground-truth statistics.
        """

        statistics = self.repository.get_statistics()

        return EmailStatisticsResponse(
            total_emails=statistics[
                "total_emails"
            ],
            normal_emails=statistics[
                "normal_emails"
            ],
            bombing_emails=statistics[
                "bombing_emails"
            ],
        )

    # ========================================================================
    # DELETE
    # ========================================================================

    def delete(
        self,
        email_id: UUID,
    ) -> EmailDeleteResponse:
        """
        Delete one email record.

        The current locked Email Management UI does not expose
        a delete action. This method is retained only for
        compatibility with existing internal callers.
        """

        email = self.repository.get_by_id(
            email_id,
        )

        if email is None:
            raise EmailNotFoundError(
                f"Email '{email_id}' was not found."
            )

        deleted = self.repository.delete_by_id(
            email_id,
        )

        if not deleted:
            raise EmailNotFoundError(
                f"Email '{email_id}' was not found."
            )

        return EmailDeleteResponse(
            email_id=email_id,
            deleted=True,
        )

    # ========================================================================
    # RESPONSE MAPPERS
    # ========================================================================

    @staticmethod
    def _to_email_response(
        email: Email,
    ) -> EmailResponse:
        """
        Convert an Email ORM object to the Email Management
        list response.

        The list response intentionally does not include raw
        email content.
        """

        return EmailResponse(
            id=email.id,
            source=email.source,
            source_identifier=email.source_identifier,
            ground_truth_label=email.ground_truth_label,
            message_id=email.message_id,
            sender=email.sender,
            recipients=email.recipients,
            subject=email.subject,
            content_hash=email.content_hash,
            received_at=email.received_at,
            collected_at=email.collected_at,
            status=email.status,
            created_at=email.created_at,
            updated_at=email.updated_at,
        )

    @staticmethod
    def _to_email_detail_response(
        email: Email,
    ) -> EmailDetailResponse:
        """
        Convert an Email ORM object to the complete Email Details
        response.

        This mapper intentionally includes only Module 02
        email-management information.
        """

        return EmailDetailResponse(
            id=email.id,

            ground_truth_label=(
                email.ground_truth_label
            ),

            source=email.source,

            source_identifier=(
                email.source_identifier
            ),

            subject=email.subject,

            sender=email.sender,

            recipients=email.recipients,

            cc=email.cc,

            bcc=email.bcc,

            reply_to=email.reply_to,

            message_id=email.message_id,

            received_at=email.received_at,

            collected_at=email.collected_at,

            content_type=email.content_type,

            mime_version=email.mime_version,

            content_hash=email.content_hash,

            raw_content=email.raw_content,

            status=email.status,

            created_at=email.created_at,

            updated_at=email.updated_at,
        )
